-- DDL completa (estrutura, sem dados) dos schemas public, private e suporte_privado,
-- montada só lendo o catálogo do Postgres. Faz o papel do pg_dump --schema-only,
-- que exigiria a senha do banco ou Docker.
-- Uso: supabase db query --linked -f api/scripts/schema/ddl.sql > ddl.json
-- search_path vazio: tudo sai qualificado com o schema (como no pg_dump).
SET search_path = '';
with
rels as (
  select c.oid, n.nspname as esquema, c.relname as nome, c.relkind, c.relrowsecurity, c.relforcerowsecurity
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname in ('public', 'suporte_privado') and c.relkind in ('r', 'v') and not c.relispartition
    and c.relname not like '\_%' -- tabelas de backup avulsas e controle de migrations
),
tabelas as (select * from rels where relkind = 'r'),
nossas_funcoes as (
  select p.oid, n.nspname as esquema, p.proname as nome
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname in ('public', 'private')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
-- Padrão de coluna que chama função nossa só pode ser aplicado depois dela existir.
defaults_adiados as (
  select distinct d.adrelid, d.adnum
  from pg_attrdef d
  join pg_depend dep on dep.classid = 'pg_attrdef'::regclass and dep.objid = d.oid and dep.refclassid = 'pg_proc'::regclass
  where dep.refobjid in (select oid from nossas_funcoes)
),
papeis as (select oid, rolname from pg_roles where rolname in ('anon', 'authenticated', 'service_role')),
secoes as (
  -- 10 enums
  select 10 as ordem, format('%I.%I', n.nspname, t.typname) as nome,
    format('CREATE TYPE %I.%I AS ENUM (%s);', n.nspname, t.typname,
      (select string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder) from pg_enum e where e.enumtypid = t.oid)) as sql
  from pg_type t join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public' and t.typtype = 'e'

  union all
  -- 20 tabelas (colunas, identidade, coluna gerada, padrões que não dependem de função nossa)
  select 20, format('%I.%I', t.esquema, t.nome),
    format(E'CREATE TABLE %I.%I (\n%s\n);', t.esquema, t.nome, (
      select string_agg(
        format('  %I %s', a.attname, format_type(a.atttypid, a.atttypmod))
        || case a.attidentity when 'a' then ' GENERATED ALWAYS AS IDENTITY' when 'd' then ' GENERATED BY DEFAULT AS IDENTITY' else '' end
        || case when a.attgenerated = 's' then format(' GENERATED ALWAYS AS (%s) STORED', pg_get_expr(d.adbin, d.adrelid)) else '' end
        || case when d.oid is not null and a.attgenerated <> 's'
                 and not exists (select 1 from defaults_adiados x where x.adrelid = a.attrelid and x.adnum = a.attnum)
                then ' DEFAULT ' || pg_get_expr(d.adbin, d.adrelid) else '' end
        || case when a.attnotnull then ' NOT NULL' else '' end,
        E',\n' order by a.attnum)
      from pg_attribute a left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
      where a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped))
  from tabelas t

  union all
  -- 30 funções (check_function_bodies = false no cabeçalho: a ordem entre elas não importa)
  select 30, format('%I.%I(%s)', f.esquema, f.nome, pg_get_function_identity_arguments(f.oid)),
    pg_get_functiondef(f.oid) || ';'
  from nossas_funcoes f

  union all
  -- 35 padrões que chamam função nossa
  select 35, format('%I.%I.%I', n.nspname, c.relname, a.attname),
    format('ALTER TABLE ONLY %I.%I ALTER COLUMN %I SET DEFAULT %s;', n.nspname, c.relname, a.attname, pg_get_expr(d.adbin, d.adrelid))
  from defaults_adiados x
  join pg_attrdef d on d.adrelid = x.adrelid and d.adnum = x.adnum
  join pg_attribute a on a.attrelid = x.adrelid and a.attnum = x.adnum
  join pg_class c on c.oid = x.adrelid join pg_namespace n on n.oid = c.relnamespace
  where c.oid in (select oid from tabelas)

  union all
  -- 40 PK/UNIQUE/EXCLUDE, 41 CHECK, 45 FK (FK por último: precisa das chaves das outras tabelas)
  select case c.contype when 'c' then 41 when 'f' then 45 else 40 end,
    format('%I.%I.%I', t.esquema, t.nome, c.conname),
    format('ALTER TABLE ONLY %I.%I ADD CONSTRAINT %I %s;', t.esquema, t.nome, c.conname, pg_get_constraintdef(c.oid))
  from pg_constraint c join tabelas t on t.oid = c.conrelid
  where c.contype in ('p', 'u', 'x', 'c', 'f')
    and (c.contype <> 'f' or c.confrelid in (select oid from tabelas) or c.confrelid = 'auth.users'::regclass)

  union all
  -- 50 índices que não pertencem a uma constraint
  select 50, format('%I.%I', t.esquema, ic.relname), pg_get_indexdef(i.indexrelid) || ';'
  from pg_index i join pg_class ic on ic.oid = i.indexrelid join tabelas t on t.oid = i.indrelid
  where not exists (select 1 from pg_constraint c where c.conindid = i.indexrelid and c.contype in ('p', 'u', 'x'))

  union all
  -- 60 views (com security_invoker e outras opções)
  select 60, format('%I.%I', v.esquema, v.nome),
    format(E'CREATE VIEW %I.%I%s AS\n%s;', v.esquema, v.nome,
      case when c.reloptions is not null then ' WITH (' || array_to_string(c.reloptions, ', ') || ')' else '' end,
      regexp_replace(pg_get_viewdef(v.oid, true), ';\s*$', ''))
  from rels v join pg_class c on c.oid = v.oid where v.relkind = 'v'

  union all
  -- 70 gatilhos das nossas tabelas
  select 70, format('%I.%I.%I', t.esquema, t.nome, tg.tgname), pg_get_triggerdef(tg.oid) || ';'
  from pg_trigger tg join tabelas t on t.oid = tg.tgrelid where not tg.tgisinternal

  union all
  -- 71 gatilhos em auth.users que chamam função nossa (cria o corretor no cadastro)
  select 71, format('auth.users.%I', tg.tgname),
    format(E'DO $do$ BEGIN\n  IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = %L AND tgrelid = %L::regclass) THEN\n    EXECUTE %L;\n  END IF;\nEND $do$;',
      tg.tgname, 'auth.users', pg_get_triggerdef(tg.oid))
  from pg_trigger tg
  where tg.tgrelid = 'auth.users'::regclass and not tg.tgisinternal and tg.tgfoid in (select oid from nossas_funcoes)

  union all
  -- 80 RLS ligado
  select 80, format('%I.%I', t.esquema, t.nome),
    format('ALTER TABLE %I.%I ENABLE ROW LEVEL SECURITY;', t.esquema, t.nome)
    || case when t.relforcerowsecurity then format(E'\nALTER TABLE %I.%I FORCE ROW LEVEL SECURITY;', t.esquema, t.nome) else '' end
  from tabelas t where t.relrowsecurity

  union all
  -- 85 policies
  select 85, format('%I.%I.%I', p.schemaname, p.tablename, p.policyname),
    format('CREATE POLICY %I ON %I.%I AS %s FOR %s TO %s%s%s;', p.policyname, p.schemaname, p.tablename, p.permissive, p.cmd,
      (select string_agg(case when r::text = 'public' then 'PUBLIC' else quote_ident(r::text) end, ', ') from unnest(p.roles) r),
      case when p.qual is not null then E'\n  USING (' || p.qual || ')' else '' end,
      case when p.with_check is not null then E'\n  WITH CHECK (' || p.with_check || ')' else '' end)
  from pg_policies p
  where p.schemaname in ('public', 'suporte_privado') and p.tablename not like '\_%'

  union all
  -- 90 uso dos schemas pelos papéis do Supabase
  select 90, 'schema ' || n.nspname,
    string_agg(format('GRANT %s ON SCHEMA %I TO %s;', a.privilege_type, n.nspname,
      case when a.grantee = 0 then 'PUBLIC' else quote_ident(r.rolname) end), E'\n' order by r.rolname nulls first, a.privilege_type)
  from pg_namespace n cross join lateral aclexplode(n.nspacl) a left join papeis r on r.oid = a.grantee
  where n.nspname in ('public', 'private', 'suporte_privado', 'extensions', 'auth') and (a.grantee = 0 or r.oid is not null)
  group by n.nspname

  union all
  -- 91 permissões de tabela e view (MAINTAIN fica de fora: só existe no Postgres 17+)
  select 91, format('%I.%I', t.esquema, t.nome),
    format('REVOKE ALL ON TABLE %I.%I FROM anon, authenticated, service_role;', t.esquema, t.nome)
    || coalesce(E'\n' || (
      select string_agg(format('GRANT %s ON TABLE %I.%I TO %s%s;', g.privs, t.esquema, t.nome, g.quem, g.opcao), E'\n' order by g.quem)
      from (
        select string_agg(a.privilege_type, ', ' order by a.privilege_type) as privs,
          case when a.grantee = 0 then 'PUBLIC' else quote_ident(r.rolname) end as quem,
          case when a.is_grantable then ' WITH GRANT OPTION' else '' end as opcao
        from aclexplode(c.relacl) a left join papeis r on r.oid = a.grantee
        where (a.grantee = 0 or r.oid is not null) and a.privilege_type <> 'MAINTAIN'
        group by 2, 3
      ) g), '')
  from rels t join pg_class c on c.oid = t.oid where c.relacl is not null

  union all
  -- 92 permissões por coluna
  select 92, format('%I.%I.%I', n.nspname, c.relname, att.attname),
    string_agg(format('GRANT %s (%I) ON TABLE %I.%I TO %s;', a.privilege_type, att.attname, n.nspname, c.relname,
      case when a.grantee = 0 then 'PUBLIC' else quote_ident(r.rolname) end), E'\n' order by r.rolname nulls first, a.privilege_type)
  from pg_attribute att join pg_class c on c.oid = att.attrelid join pg_namespace n on n.oid = c.relnamespace
  cross join lateral aclexplode(att.attacl) a left join papeis r on r.oid = a.grantee
  where c.oid in (select oid from rels) and att.attacl is not null and (a.grantee = 0 or r.oid is not null)
  group by n.nspname, c.relname, att.attname

  union all
  -- 93 permissões de sequência (as de identidade nascem com a tabela)
  select 93, format('%I.%I', n.nspname, c.relname),
    (select string_agg(format('GRANT %s ON SEQUENCE %I.%I TO %s;', g.privs, n.nspname, c.relname, g.quem), E'\n' order by g.quem)
     from (
       select string_agg(a.privilege_type, ', ' order by a.privilege_type) as privs,
         case when a.grantee = 0 then 'PUBLIC' else quote_ident(r.rolname) end as quem
       from aclexplode(c.relacl) a left join papeis r on r.oid = a.grantee
       where a.grantee = 0 or r.oid is not null group by 2
     ) g)
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname in ('public', 'suporte_privado') and c.relkind = 'S' and c.relacl is not null

  union all
  -- 94 permissões de função (sem ACL própria = padrão do Postgres: PUBLIC executa)
  select 94, format('%I.%I(%s)', f.esquema, f.nome, pg_get_function_identity_arguments(f.oid)),
    format('REVOKE ALL ON FUNCTION %s FROM PUBLIC;', f.oid::regprocedure)
    || coalesce(E'\n' || (
      select string_agg(format('GRANT EXECUTE ON FUNCTION %s TO %s;', f.oid::regprocedure,
        case when a.grantee = 0 then 'PUBLIC' else quote_ident(r.rolname) end), E'\n' order by r.rolname nulls first)
      from aclexplode(p.proacl) a left join papeis r on r.oid = a.grantee
      where a.grantee = 0 or r.oid is not null), '')
  from nossas_funcoes f join pg_proc p on p.oid = f.oid where p.proacl is not null

  union all
  -- 95 tabelas na publicação do Realtime (só onde a publicação existir)
  select 95, format('publication %I %I.%I', p.pubname, n.nspname, c.relname),
    format(E'DO $do$ BEGIN\n  IF EXISTS (SELECT 1 FROM pg_publication WHERE pubname = %L)\n     AND NOT EXISTS (SELECT 1 FROM pg_publication_tables WHERE pubname = %L AND schemaname = %L AND tablename = %L) THEN\n    EXECUTE %L;\n  END IF;\nEND $do$;',
      p.pubname, p.pubname, n.nspname, c.relname, format('ALTER PUBLICATION %I ADD TABLE %I.%I', p.pubname, n.nspname, c.relname))
  from pg_publication_rel pr join pg_publication p on p.oid = pr.prpubid
  join pg_class c on c.oid = pr.prrelid join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public'
)
select ordem, nome, sql from secoes order by ordem, nome;
